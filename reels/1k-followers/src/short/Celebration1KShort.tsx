import { Audio } from "@remotion/media";
import {
  AbsoluteFill,
  interpolate,
  Sequence,
  Series,
  staticFile,
  useCurrentFrame,
} from "remotion";
import { DigitsScene } from "./DigitsScene";
import { OutroBlock } from "./OutroBlock";
import { SnapScene } from "./SnapScene";
import { CREAM, INK, ORANGE, SNAP, clamp } from "./style";
import { ThanksBlock } from "./ThanksBlock";

// Skewed colour panel that covers the cut, then exits the other side.
const Wipe: React.FC<{ color: string }> = ({ color }) => {
  const frame = useCurrentFrame();
  return (
    <AbsoluteFill
      style={{
        backgroundColor: color,
        rotate: "-12deg",
        scale: "1.6",
        translate: interpolate(frame, [0, 6, 12], ["-190% 0px", "0% 0px", "190% 0px"], {
          ...clamp,
          easing: [SNAP, SNAP],
        }),
      }}
    />
  );
};

export const Celebration1KShort: React.FC = () => (
  <AbsoluteFill style={{ backgroundColor: CREAM }}>
    <Series>
      <Series.Sequence name="Snap" durationInFrames={60}>
        <SnapScene />
      </Series.Sequence>
      <Series.Sequence name="Digits" durationInFrames={60}>
        <DigitsScene />
      </Series.Sequence>
      <Series.Sequence name="Thanks" durationInFrames={60}>
        <ThanksBlock />
      </Series.Sequence>
      <Series.Sequence name="Outro" durationInFrames={90}>
        <OutroBlock />
      </Series.Sequence>
    </Series>

    <Sequence name="Wipe 1" from={54} durationInFrames={12}>
      <Wipe color={INK} />
    </Sequence>
    <Sequence name="Wipe 2" from={114} durationInFrames={12}>
      <Wipe color={CREAM} />
    </Sequence>
    <Sequence name="Wipe 3" from={174} durationInFrames={12}>
      <Wipe color={ORANGE} />
    </Sequence>

    {/* Generated by audio_short.py */}
    <Audio src={staticFile("soundtrack-short.wav")} />
  </AbsoluteFill>
);
